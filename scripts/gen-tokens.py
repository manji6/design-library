#!/usr/bin/env python3
"""DESIGN.md のフロントマター（tokens: 以下）から tokens.css を生成する。

対応するフロントマターの形は、2スペースインデントの入れ子マップと
スカラー値だけの最小サブセット。値に引用符があれば外す。
使い方: gen-tokens.py <DESIGN.md> <出力 tokens.css>
"""
import re
import sys


def parse_front_matter(text):
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        raise SystemExit("front matter not found")
    return m.group(1)


def parse_tokens(fm):
    lines = fm.splitlines()
    tokens = {}
    in_tokens = False
    group = None
    for line in lines:
        if re.match(r"^tokens:\s*$", line):
            in_tokens = True
            continue
        if in_tokens:
            if line and not line.startswith(" "):
                break
            gm = re.match(r"^  ([A-Za-z0-9_-]+):\s*$", line)
            if gm:
                group = gm.group(1)
                tokens[group] = {}
                continue
            vm = re.match(r"^    ([A-Za-z0-9_-]+):\s*(.+?)\s*$", line)
            if vm and group:
                val = vm.group(2)
                if len(val) >= 2 and val[0] == val[-1] and val[0] in "\"'":
                    val = val[1:-1]
                tokens[group][vm.group(1)] = val
                continue
            raise SystemExit(f"unsupported line in tokens: {line!r}")
    if not tokens:
        raise SystemExit("tokens section is empty")
    return tokens


def main():
    src, out = sys.argv[1], sys.argv[2]
    tokens = parse_tokens(parse_front_matter(open(src, encoding="utf-8").read()))
    lines = [
        "/* GENERATED by scripts/gen-tokens.py from DESIGN.md — do not edit by hand. */",
        ":root {",
    ]
    for group, items in tokens.items():
        for key, val in items.items():
            lines.append(f"  --{group}-{key}: {val};")
    lines.append("}")
    with open(out, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
